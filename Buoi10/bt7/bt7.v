module bt7(
    SW,
    CLOCK_50,
    HEX0, HEX1, HEX2, HEX3,
    HEX4, HEX5, HEX6, HEX7
);

//////////////////////////////////////////////////
// INPUT - OUTPUT
//////////////////////////////////////////////////

input [1:0] SW;
input CLOCK_50;

output reg [6:0] HEX0, HEX1, HEX2, HEX3;
output reg [6:0] HEX4, HEX5, HEX6, HEX7;

wire RS;
assign RS = SW[1];

//////////////////////////////////////////////////
// STATE
//////////////////////////////////////////////////

parameter s0 = 3'b000;
parameter s1 = 3'b001;
parameter s2 = 3'b010;
parameter s3 = 3'b011;
parameter s4 = 3'b100;
parameter s5 = 3'b101;
parameter s6 = 3'b110;
parameter s7 = 3'b111;

reg [2:0] current_state, next_state;

//////////////////////////////////////////////////
// CLOCK 4Hz
//////////////////////////////////////////////////

integer q = 0;
reg clock_4hz = 1'b0;

// CLOCK_50 = 50MHz
// f = 4Hz
// Toggle mỗi 6_250_000 xung

always @(posedge CLOCK_50)
begin
    q <= q + 1;

    if(q == 6250000)
    begin
        clock_4hz <= ~clock_4hz;
        q <= 0;
    end
end

//////////////////////////////////////////////////
// NEXT STATE
//////////////////////////////////////////////////

always @(*)
begin
    case(current_state)

        s0: next_state = s1;
        s1: next_state = s2;
        s2: next_state = s3;
        s3: next_state = s4;
        s4: next_state = s5;
        s5: next_state = s6;
        s6: next_state = s7;
        s7: next_state = s0;

        default: next_state = s0;

    endcase
end

//////////////////////////////////////////////////
// STATE REGISTER
// clk cạnh lên
// reset đồng bộ tích cực mức cao
//////////////////////////////////////////////////

always @(posedge clock_4hz)
begin

    if(RS)
        current_state <= s0;

    else
        current_state <= next_state;

end

//////////////////////////////////////////////////
// DISPLAY : HI-BABY
// Dịch từ trái sang phải
//////////////////////////////////////////////////

always @(*)
begin

    case(current_state)

    //////////////////////////////////////////////////
    // s0
    //////////////////////////////////////////////////

    s0:
    begin
        HEX7 = 7'b1111111;
        HEX6 = 7'b1001000; // H
        HEX5 = 7'b1111001; // I
        HEX4 = 7'b0111111; // -
        HEX3 = 7'b0000011; // B
        HEX2 = 7'b0001000; // A
        HEX1 = 7'b0000011; // B
        HEX0 = 7'b0010001; // Y
    end

    //////////////////////////////////////////////////
    // s1
    //////////////////////////////////////////////////

    s1:
    begin
        HEX7 = 7'b0010001; // Y
        HEX6 = 7'b1111111;
        HEX5 = 7'b1001000; // H
        HEX4 = 7'b1111001; // I
        HEX3 = 7'b0111111; // -
        HEX2 = 7'b0000011; // B
        HEX1 = 7'b0001000; // A
        HEX0 = 7'b0000011; // B
    end

    //////////////////////////////////////////////////
    // s2
    //////////////////////////////////////////////////

    s2:
    begin
        HEX7 = 7'b0000011; // B
HEX6 = 7'b0010001; // Y
        HEX5 = 7'b1111111;
        HEX4 = 7'b1001000; // H
        HEX3 = 7'b1111001; // I
        HEX2 = 7'b0111111; // -
        HEX1 = 7'b0000011; // B
        HEX0 = 7'b0001000; // A
    end

    //////////////////////////////////////////////////
    // s3
    //////////////////////////////////////////////////

    s3:
    begin
        HEX7 = 7'b0001000; // A
        HEX6 = 7'b0000011; // B
        HEX5 = 7'b0010001; // Y
        HEX4 = 7'b1111111;
        HEX3 = 7'b1001000; // H
        HEX2 = 7'b1111001; // I
        HEX1 = 7'b0111111; // -
        HEX0 = 7'b0000011; // B
    end

    //////////////////////////////////////////////////
    // s4
    //////////////////////////////////////////////////

    s4:
    begin
        HEX7 = 7'b0000011; // B
        HEX6 = 7'b0001000; // A
        HEX5 = 7'b0000011; // B
        HEX4 = 7'b0010001; // Y
        HEX3 = 7'b1111111;
        HEX2 = 7'b1001000; // H
        HEX1 = 7'b1111001; // I
        HEX0 = 7'b0111111; // -
    end

    //////////////////////////////////////////////////
    // s5
    //////////////////////////////////////////////////

    s5:
    begin
        HEX7 = 7'b0111111; // -
        HEX6 = 7'b0000011; // B
        HEX5 = 7'b0001000; // A
        HEX4 = 7'b0000011; // B
        HEX3 = 7'b0010001; // Y
        HEX2 = 7'b1111111;
        HEX1 = 7'b1001000; // H
        HEX0 = 7'b1111001; // I
    end

    //////////////////////////////////////////////////
    // s6
    //////////////////////////////////////////////////

    s6:
    begin
        HEX7 = 7'b1111001; // I
        HEX6 = 7'b0111111; // -
        HEX5 = 7'b0000011; // B
        HEX4 = 7'b0001000; // A
        HEX3 = 7'b0000011; // B
        HEX2 = 7'b0010001; // Y
        HEX1 = 7'b1111111;
        HEX0 = 7'b1001000; // H
    end

    //////////////////////////////////////////////////
    // s7
    //////////////////////////////////////////////////

    s7:
    begin
        HEX7 = 7'b1001000; // H
        HEX6 = 7'b1111001; // I
        HEX5 = 7'b0111111; // -
        HEX4 = 7'b0000011; // B
        HEX3 = 7'b0001000; // A
        HEX2 = 7'b0000011; // B
        HEX1 = 7'b0010001; // Y
        HEX0 = 7'b1111111;
    end

    //////////////////////////////////////////////////
    // DEFAULT
    //////////////////////////////////////////////////

    default:
    begin
        HEX0 = 7'b1111111;
        HEX1 = 7'b1111111;
        HEX2 = 7'b1111111;
        HEX3 = 7'b1111111;
        HEX4 = 7'b1111111;
        HEX5 = 7'b1111111;
        HEX6 = 7'b1111111;
        HEX7 = 7'b1111111;
    end

    endcase

end

endmodule